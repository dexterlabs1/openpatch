#!/usr/bin/env python3
"""Re-extract exact integer tables; fetches pins and executes no DSP."""
import argparse
import re
from pathlib import Path
from fetch import DEFAULT_CACHE, ROOT, fetch

def generate(cache):
    src=(cache/'grids/resources.cc').read_text()
    tables={n:[int(v,0) for v in re.findall(r'0x[0-9a-fA-F]+|\d+',body)]
            for n,body in re.findall(r'const prog_uint(?:8|32)_t (\w+)\[\] PROGMEM = \{(.*?)\};',src,re.S)}
    out='// Copyright 2011 Emilie Gillet. GPL-3.0-or-later.\n// Exact tables from pichenettes/eurorack f4cfa7697095a28d292bff758beb51deb49b5a86, grids/resources.cc.\n// Generated by scripts/grids_reference/generate_resources.py; no resampling.\n\n'
    for source,name in [('lut_res_euclidean','EUCLIDEAN'),('lut_res_tempo_phase_increment','TEMPO_PHASE_INCREMENT')]:
        vals=tables[source];out+=f'pub const {name}: [u32; {len(vals)}] = [\n'
        for i in range(0,len(vals),8):out+='    '+', '.join(map(str,vals[i:i+8]))+',\n'
        out+='];\n\n'
    out+='pub const NODES: [[u8; 96]; 25] = [\n'
    for i in range(25):
        vals=tables[f'node_{i}'];assert len(vals)==96
        out+='    [\n'
        for j in range(0,96,16):out+='        '+', '.join(map(str,vals[j:j+16]))+',\n'
        out+='    ],\n'
    out+='];\n\npub const DRUM_MAP: [[usize; 5]; 5] = [\n    [10, 8, 0, 9, 11],\n    [15, 7, 13, 12, 6],\n    [18, 14, 4, 5, 3],\n    [23, 16, 21, 1, 2],\n    [24, 19, 17, 20, 22],\n];\n'
    return out

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache',type=Path,default=DEFAULT_CACHE)
    parser.add_argument('--output',type=Path,default=ROOT/'crates/openpatch-core/src/rhythm_terrain/resources.rs')
    args=parser.parse_args();fetch(args.cache);args.output.write_text(generate(args.cache))
