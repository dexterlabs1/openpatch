#!/usr/bin/env python3
"""Original normalized Blackman-windowed sinc kernels; MIT, stdlib only.
Run from any directory to reproduce core/src/svf_resampler_kernels.rs.
Matches screen.py's NumPy definition within f64 rounding.
"""
from pathlib import Path
from math import sin, cos, pi
ROOT=Path(__file__).resolve().parent
specs=[(129,2,.45,False),(33,4,1.,True),(17,8,2.,True),(33,16,4.,True)]

def kernel(n, rate, cutoff, halfband):
    h=[]
    for i in range(n):
        t=i-(n-1)//2
        window=.42-.5*cos(2*pi*i/(n-1))+.08*cos(4*pi*i/(n-1))
        sinc=2*cutoff/rate if t==0 else sin(2*pi*cutoff*t/rate)/(pi*t)
        h.append(0. if halfband and t!=0 and t%2==0 else sinc*window)
    total=sum(h)
    # Enforce exact symmetry by using the first side; reduces runtime MACs.
    for i in range(n//2):h[n-1-i]=h[i]
    return [v/total for v in h]

out=['// Generated by ../../generate_kernels.py. Original design, MIT.\n']
for n,r,c,hb in specs:
    out.append(f'pub(super) const H{r}: [f64; {n}] = [\n')
    out.extend(f'    {v:.17e},\n' for v in kernel(n,r,c,hb))
    out.append('];\n')
(ROOT/'core/src/svf_resampler_kernels.rs').write_text(''.join(out))
